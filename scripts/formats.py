"""docs/formats.md from the evidence scripts/formats.sh gathers: the readers, the
tests that recorded them, the corpus's expected summaries, the real-world run, and
the last soak report."""
import collections, datetime, glob, os, re, subprocess, sys

readers_tsv, tested_tsv, real_log = sys.argv[1], sys.argv[2], sys.argv[3] if len(sys.argv) > 3 else ""

ORDER = ["Images", "ThreeD", "Data", "Docs", "Sheets", "Text", "Archives"]
CRATE = {"Images": "libfileparser-images", "ThreeD": "libfileparser-3d", "Data": "libfileparser-data", "Docs": "libfileparser-docs",
         "Sheets": "libfileparser-sheets", "Text": "libfileparser-text", "Archives": "libfileparser-archives"}
SOAK_TARGET = {"Images": "images", "ThreeD": "threed", "Data": "data", "Docs": "docs", "Sheets": "sheets", "Text": "text", "Archives": "archives"}

readers = []
for line in open(readers_tsv):
    cat, rid, name, exts, also = (line.rstrip("\n").split("\t") + [""] * 5)[:5]
    readers.append((cat, rid, name, exts.split(), also.split()))

# Conformance and fuzz: passed only if every recorded run passed.
tested = collections.defaultdict(lambda: collections.defaultdict(list))
if os.path.exists(tested_tsv):
    for line in open(tested_tsv):
        suite, rid, ok = line.rstrip("\n").split("\t")
        tested[suite][rid].append(ok == "true")
def passed(suite, rid):
    runs = tested[suite].get(rid)
    return bool(runs) and all(runs)

# A committed corpus file that opens as the reader.
corpus = collections.Counter()
for f in glob.glob("corpus/expected/**/*.toml", recursive=True):
    m = re.search(r'^loader = "([^"]+)"', open(f).read(), re.M)
    if m:
        corpus[m.group(1)] += 1

# Real-world: "<reader>: N files — K opened as <reader>, …".
real = {}
if real_log and os.path.exists(real_log):
    for m in re.finditer(r"^([\w.+-]+): (\d+) files — (\d+) opened as \1", open(real_log).read(), re.M):
        real[m.group(1)] = (int(m.group(3)), int(m.group(2)))

# Soak: readers that existed at the last soak's commit, in a target with no finding
# that still reproduces.
soak_commit, soak_date, soak_clean, soaked_ids = None, None, {}, set()
if os.path.exists("soak/report.md"):
    rep = open("soak/report.md").read()
    m = re.search(r"Finished (\S+)\. Commit: (\w+)", rep)
    if m:
        soak_date, soak_commit = m.group(1)[:10], m.group(2)
    for t in SOAK_TARGET.values():
        row = re.search(rf"^\| {t} \|.*$", rep, re.M)
        still = re.search(rf"\*\*{t}\*\* (?!no longer reproduces)", rep)
        soak_clean[t] = bool(row) and not still
    if soak_commit:
        try:
            out = subprocess.run(["git", "grep", "-h", "-o", r'ReaderInfo::new("[^"]*"', soak_commit, "--", "crates"], capture_output=True, text=True).stdout
            soaked_ids = set(re.findall(r'"([^"]+)"', out))
        except OSError:
            pass

tick = lambda b: "✅" if b else "⬜"
def row(cat, rid, name, exts, also):
    c = corpus[rid]
    r = real.get(rid)
    real_cell = "—" if r is None else f"{tick(r[0] == r[1])} {r[0]}/{r[1]}"
    soak = tick(rid in soaked_ids and soak_clean.get(SOAK_TARGET[cat], False))
    shown = " ".join(f"`.{e}`" for e in exts[:8]) + (" …" if len(exts) > 8 else "")
    return f"| `{rid}` | {name} | {shown or '(by content)'} | {tick(c > 0)} | {tick(passed('conformance', rid))} | {tick(passed('fuzz', rid))} | {real_cell} | {soak} |"

out = []
out.append("# Formats: every reader, and what tested it\n")
out.append(f"Generated by `scripts/formats.sh` on {datetime.date.today().isoformat()}; don't edit by hand, rerun it. Each tick is from evidence, never written in:\n")
out.append("| Column | Ticked when |\n|---|---|")
out.append("| Corpus | A committed corpus file opens as this reader (`corpus/expected/`, checked by `cargo test -p viewer-corpus`) |")
out.append("| Conformance | `libfileparser-testkit`'s conformance suite passed on it (recorded with `LFP_TESTED`) |")
out.append("| Fuzz | The testkit's mutation fuzzer ran it on samples, without a panic or hang (recorded with `LFP_TESTED`; 64 inputs a sample by default) |")
out.append("| Real files | Real files sorted as this format (`corpus/real/`, fetched by `corpus/fetch-real.sh`) opened as it: opened/total; the rest were broken, encrypted or another format's. — when none were fetched |")
soak_note = f"the last soak report (`soak/report.md`, {soak_date}, commit `{soak_commit}`)" if soak_commit else "a soak report (none found)"
out.append(f"| Soak | It existed at {soak_note}, and its category's coverage-guided target left no finding that still reproduces. Readers added since aren't ticked until the next soak |\n")

out.append("## Summary\n")
out.append("| Category | Library | Readers | Corpus | Conformance | Fuzz | Real files | Soak |\n|---|---|---|---|---|---|---|---|")
for cat in ORDER:
    rs = [r for r in readers if r[0] == cat]
    n = len(rs)
    count = lambda f: sum(1 for r in rs if f(r[1]))
    real_n = sum(1 for r in rs if r[1] in real)
    out.append(f"| {cat.replace('ThreeD', '3D')} | `{CRATE[cat]}` | {n} | {count(lambda i: corpus[i] > 0)} | {count(lambda i: passed('conformance', i))} | {count(lambda i: passed('fuzz', i))} | {real_n} | {count(lambda i: i in soaked_ids and soak_clean.get(SOAK_TARGET[cat], False))} |")
total = len(readers)
out.append(f"| **All** | | **{total}** | | | | | |\n")
for cat in ORDER:
    rs = sorted((r for r in readers if r[0] == cat), key=lambda r: r[1])
    out.append(f"## {cat.replace('ThreeD', '3D')} (`{CRATE[cat]}`, {len(rs)} readers)\n")
    out.append("| Reader | Name | Extensions | Corpus | Conformance | Fuzz | Real files | Soak |\n|---|---|---|---|---|---|---|---|")
    out.extend(row(*r) for r in rs)
    out.append("")
print("\n".join(out))
